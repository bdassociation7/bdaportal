# Build SQL INSERT
rows = []
for lesson in lessons_data:
    module_id = module_ids[lesson["module"]]
    title = lesson["title"].replace("'", "''")
    desc = lesson["desc"].replace("'", "''")
    rows.append(f"""(
  gen_random_uuid(), '{module_id}',
  '{title}', '{title}',
  '{desc}', '{desc}',
  '{{}}', '{{}}',
  ARRAY['فهم المفاهيم الأساسية', 'تطبيق المعرفة عملياً', 'ربط المحتوى بالكفاءات المهنية'],
  ARRAY['فهم المفاهيم الأساسية', 'تطبيق المعرفة عملياً', 'ربط المحتوى بالكفاءات المهنية'],
  1, {lesson['order']}, false, 70, true, 'ar'
)""")

sql = "INSERT INTO curriculum_lessons (id, module_id, title, title_ar, description, description_ar, content, content_ar, learning_objectives, learning_objectives_ar, estimated_duration_hours, order_index, quiz_required, quiz_passing_score, is_published, exam_language) VALUES\n"
sql += ",\n".join(rows) + ";"

with open('/home/ubuntu/bdaportal/insert_ar_lessons.sql', 'w') as f:
    f.write(sql)

print(f"Generated SQL for {len(rows)} lessons")
print("Saved to insert_ar_lessons.sql")

# Execute the SQL
result = subprocess.run(
    ['manus-mcp-cli', 'tool', 'call', 'execute_sql', '--server', 'supabase', '--input',
     json.dumps({
         "project_id": "dfsbzsxuursvqwnzruqt",
         "query": sql
     })],
    capture_output=True, text=True
)

